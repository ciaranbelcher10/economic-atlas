#!/usr/bin/env python3
"""v1.7.57: the Markets FX chart and the Dollarise view must start at the same year.

For every page on a World Bank annual rate (fx_config.ANNUAL), the country's
fx_to_usd.floor and fx_config.SERIES_START must agree. v1.7.56 set floors on
Peru, Iceland and Pakistan but no SERIES_START, so their Markets charts ran
back to 1960/1988 in older units and flattened everything since.

Also checks that the built FX file (data-fx-*.json), when present, does not
start before the floor (it is regenerated by fetch_fx_daily.py each run).

    python3 tools/fx_floor_gate.py      # exit 1 on any mismatch
"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import fx_config as C  # noqa: E402


def main():
    bad, checked, stale, legacy = [], 0, [], []
    for country, (home, suffix, _q) in C.COUNTRY_FX.items():
        if home not in C.ANNUAL:
            continue
        try:
            fx = json.loads((ROOT / C.data_file(suffix)).read_text())["fx_to_usd"]
        except Exception:
            continue
        floor = fx.get("floor")
        start = C.SERIES_START.get(home, (None,))[0]
        checked += 1
        if floor and str(floor)[:4] != start:
            bad.append(f"{country}: fx_to_usd.floor {floor} but SERIES_START[{home}] {start}")
        if start and not floor:
            legacy.append(f"{country}: SERIES_START[{home}] {start}, no fx_to_usd.floor (pre-v1.7.51 page)")
        fxf = ROOT / C.fx_file(suffix)
        if floor and fxf.exists():
            for p in json.loads(fxf.read_text()).get("pairs", []):
                if p.get("points") and str(p["points"][0][0])[:4] < str(floor)[:4]:
                    stale.append(f"{country} {p['key']} starts {p['points'][0][0]}")
    for b in bad:
        print("FAIL " + b)
    for s in legacy:
        print("INFO " + s)
    for s in stale:
        print("INFO built FX file predates the fix, regenerated next run: " + s)
    print(f"fx floor gate: {checked} annual-rate pages, {len(bad)} mismatch(es)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
