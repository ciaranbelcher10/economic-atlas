#!/usr/bin/env python3
"""Tests for the methodology-by-economy checks in tools/generated_pages_gate.py (v1.9.15).

The page is generated by methodology_by_economy.py from the same catalogue as the indicator pages, and the gate
re-derives its facts from the data files with its own copy of the rules. These tests break the generator and the
module in ways that matter, and doctor the data so that a hand-written note's condition stops holding, and require
the gate to exit 1 with the right message each time. A crash does not count as a catch.

  - positive control: the repo as it is passes;
  - 12 breakages (a missing page, broken links, a dropped economy, a doubled row, truncated labels, wrong
    frequencies, wrong or missing gaps, a note on the wrong economy, a note that outlives its condition, a
    missing generated note, a wrong gap-table count);
  - doctored data: Switzerland's growth label loses its series id. The real module must then drop that note (and
    pass); a module whose check always says yes must be caught.

Run from the repo root:  python3 tools/test_methodology_gate.py     (about two minutes)
"""
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GATE = ROOT / "tools" / "generated_pages_gate.py"
GEN = (ROOT / "generate_indicator_pages.py").read_text(encoding="utf-8")
MOD = (ROOT / "methodology_by_economy.py").read_text(encoding="utf-8")
fails = []
ran = 0


def check(cond, msg):
    if not cond:
        fails.append(msg)
        print("FAIL", msg)


def repo_copy(edit=None):
    d = Path(tempfile.mkdtemp(prefix="tmg_"))
    for pat in ("*.json", "*.html", "*.py"):
        for f in glob.glob(str(ROOT / pat)):
            shutil.copy(f, d / os.path.basename(f))
    # the page links to the site's css, js and images: link them in so the gate's link check has something to resolve
    for f in ROOT.iterdir():
        if f.is_file() and not (d / f.name).exists():
            os.symlink(f, d / f.name)
    if edit:
        edit(d)
    return d


def run_gate(repo):
    global ran
    ran += 1
    return subprocess.run([sys.executable, str(GATE), "--repo", str(repo), "--max-fails", "1000"], capture_output=True, text=True, timeout=300,
                          env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1"))


def caught(name, r, expect):
    out = r.stdout + r.stderr
    fl = [ln for ln in out.splitlines() if ln.startswith("FAIL")]
    ok = r.returncode == 1 and "Traceback" not in r.stderr and any(expect in ln for ln in fl)
    check(ok, f"{name}: expected exit 1 with a FAIL line containing {expect!r}; got rc={r.returncode}, "
              f"{len(fl)} FAIL lines, first: {fl[0][:160] if fl else out[-240:]!r}")


def edit_file(fname, old, new, count_ok=1):
    src = (ROOT / fname).read_text(encoding="utf-8")
    assert src.count(old) == count_ok, f"{fname}: anchor appears {src.count(old)} times: {old[:70]!r}"

    def apply(d):
        p = d / fname
        p.write_text(p.read_text(encoding="utf-8").replace(old, new, 1), encoding="utf-8")
    return apply


def both(*edits):
    def apply(d):
        for e in edits:
            e(d)
    return apply


# ---------------------------------------------------------------- the committed page must exist
# With the page committed, a gate that staged the committed copy could not notice a generator that stopped producing
# it (v1.9.15 fixed exactly that). Without the committed page this test would pass vacuously, so insist on it.
check((ROOT / "methodology-by-economy.html").exists(),
      "methodology-by-economy.html is not committed, so the 'page not generated' case below would prove nothing")

# ---------------------------------------------------------------- positive control
d = repo_copy()
try:
    r = run_gate(d)
    check(r.returncode == 0 and "ok (0 failures)" in r.stdout and "methodology economies" in r.stdout,
          f"positive control must pass and report the methodology counts: {r.stdout[-300:]} {r.stderr[-200:]}")
finally:
    shutil.rmtree(d, ignore_errors=True)

# ---------------------------------------------------------------- breakages
CASES = [
    ("page not generated",
     edit_file("generate_indicator_pages.py", '    write_page("methodology-by-economy.html", render_methodology_page(catalogue_by_country))\n', ""),
     "was not generated"),
    ("shell paths not rewritten for a root page",
     edit_file("generate_indicator_pages.py", "    return out.replace('\"../', '\"')\n\n\n", "    return out\n\n\n"),
     "does not resolve"),
    ("an economy dropped",
     edit_file("methodology_by_economy.py", "    for country in sorted(countries):\n", "    for country in sorted(countries)[1:]:\n"),
     "methodology documents"),
    ("a row written twice",
     edit_file("methodology_by_economy.py", "    out.append('</tbody></table>')\n    out.append('<p class=\"mb-gaps\">",
               "    out.append(out[-1] if False else '')\n    out.extend(out[-2:-1] if rows else [])\n    out.append('</tbody></table>')\n    out.append('<p class=\"mb-gaps\">"),
     "twice"),
    ("series labels truncated",
     edit_file("methodology_by_economy.py", '        label = (s.get("label") or "").strip()\n', '        label = (s.get("label") or "").strip()[:18]\n'),
     "differs from the data"),
    ("wrong frequency word",
     edit_file("methodology_by_economy.py", 'FREQ_WORD = {"months": "Monthly",', 'FREQ_WORD = {"months": "Weekly",'),
     "frequency"),
    ("the US shown as lacking an exchange rate",
     edit_file("methodology_by_economy.py", 'FX_BASE = {"US"}', "FX_BASE = set()"),
     "'Not tracked' says"),
    ("a core indicator dropped from the gap rules",
     edit_file("methodology_by_economy.py", '    ("Policy interest rate", ["interest-rate"]),\n', ""),
     "'Not tracked' says"),
    ("gap table count off by one",
     edit_file("methodology_by_economy.py", "<td>{len(lacking)}</td>", "<td>{len(lacking) + 1}</td>"),
     "gap table for"),
    ("a note printed on the wrong economy",
     edit_file("methodology_by_economy.py", '    ("Poland",\n     "The trade balance is Eurostat', '    ("Portugal",\n     "The trade balance is Eurostat'),
     "carries the note meant for poland"),
    ("generated OECD note missing",
     edit_file("methodology_by_economy.py", "    if oecd:\n", "    if False and oecd:\n"),
     "OECD QNA note shown=False"),
    ("a theme lost from the registry",
     edit_file("methodology_by_economy.py", '    ("Public finances", ["government-debt", "government-net-debt", "government-budget", "government-debt-interest"]),\n', ""),
     "has no theme"),
]
for name, edit, expect in CASES:
    d = repo_copy(edit)
    try:
        caught(name, run_gate(d), expect)
    finally:
        shutil.rmtree(d, ignore_errors=True)


# ---------------------------------------------------------------- a note that outlives its condition
def drop_swiss_series_id(d):
    p = d / "data-ch.json"
    j = json.loads(p.read_text(encoding="utf-8"))
    lab = j["series"]["gdp_growth"]["label"]
    assert "CLVMNACSAB1GQCH" in lab, f"data moved on: {lab}"
    j["series"]["gdp_growth"]["label"] = lab.replace("CLVMNACSAB1GQCH", "OTHERSERIES")
    p.write_text(json.dumps(j), encoding="utf-8")


d = repo_copy(drop_swiss_series_id)
try:
    r = run_gate(d)
    check(r.returncode == 0, f"the real module must drop a note whose condition no longer holds, and pass: {r.stdout[-300:]} {r.stderr[-200:]}")
finally:
    shutil.rmtree(d, ignore_errors=True)

always_yes = edit_file("methodology_by_economy.py",
                       '     lambda c: "CLVMNACSAB1GQCH" in c.label("Switzerland", "gdp_growth")),', "     lambda c: True),")
d = repo_copy(both(drop_swiss_series_id, always_yes))
try:
    caught("a note check that always says yes", run_gate(d), "note 'sporting events' shown=True")
finally:
    shutil.rmtree(d, ignore_errors=True)

print(f"test_methodology_gate: {'FAILED' if fails else 'ok'} ({len(fails)} failures, {ran} gate runs)")
sys.exit(1 if fails else 0)
